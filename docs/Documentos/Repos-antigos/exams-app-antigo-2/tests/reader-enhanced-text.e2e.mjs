import assert from 'node:assert/strict';
import path from 'node:path';
import {mkdir,writeFile} from 'node:fs/promises';
import {PDFDocument,StandardFonts,rgb} from 'pdf-lib';
import {chromium} from 'playwright';

const pdfdir=path.resolve('prototype');
await mkdir(pdfdir,{recursive:true});
const out=path.join(pdfdir,'exam-app-0.1.1__pdfs__edital-dou-03-07-2026.pdf');
const pdf=await PDFDocument.create(),pg=pdf.addPage([612,792]),font=await pdf.embedFont(StandardFonts.Helvetica);
const left=[
 'CAPITULO 1 NORMAS GERAIS.', 'O concurso possui inscricoes abertas.',
 'Os candidatos deverao preencher os requisitos.', 'A avaliacao sera realizada no prazo.',
 'O edital informa as regras publicadas.', 'A admissao depende de aprovacao.',
 'A prova objetiva tera tempo determinado.', 'Os locais serao informados por edital.',
 'O conteudo programatico esta descrito.', 'O prazo de recurso segue a norma.',
 'A jornada obedecera ao regulamento.'
];
const right=[
 'CAPITULO 2 PROCEDIMENTOS.', 'Os participantes deverao confirmar os dados.',
 'A secretaria publicara as comunicacoes.', 'O protocolo garante prazo regular.',
 'A lista final sera divulgada no portal.', 'A documentacao precisa estar completa.',
 'O candidato podera apresentar impugnacao.', 'As fases seguem calendario oficial.',
 'O resultado provisoriamente sera divulgado.', 'A classificacao aplica os criterios.',
 'O ato de convocacao encerra a selecao.'
];
for(let i=0;i<left.length;i++)pg.drawText(left[i],{x:30,y:735-i*30,font,size:10,color:rgb(0,0,0)});
for(let i=0;i<right.length;i++)pg.drawText(right[i],{x:330,y:735-i*30,font,size:10,color:rgb(0,0,0)});
await writeFile(out,await pdf.save());

const root=path.resolve('prototype'),assets=root;
await mkdir(assets,{recursive:true});
const report={created:new Date().toISOString(),checks:[],errors:[],limits:[
 'Two-column extracted PDF fixture is generated by pdf-lib, not an authenticated Brazilian DOU original.',
 'Text-mode annotations do not yet overlay canvas coordinates; scanned OCR is not available.'
]};
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const base='http://127.0.0.1:8765/exam-app-0.1.1__index.html';
try{
 for(const width of [390,1366]){
  const context=await browser.newContext({viewport:{width,height:900},reducedMotion:'reduce'});
  const page=await context.newPage();page.on('pageerror',e=>report.errors.push(e.message));
  try{
   await page.goto(base+'#edital',{waitUntil:'domcontentloaded'});
   await page.locator('.reader-tools [data-reader-mode]').waitFor({timeout:25000});
   const layout=await page.evaluate(()=>{const v=document.querySelector('.view'),p=document.querySelector('.page'),main=document.querySelector('.main');return {
     route:location.hash,main:main?.className,viewRect:v?.getBoundingClientRect().toJSON(),
     viewDisplay:v&&getComputedStyle(v).display,pageStyle:p?.getAttribute('style'),
     parent:p?.parentElement?.className,app:document.querySelector('#app')?.className
   };});
   assert.ok(layout.viewRect?.width>width/2,'PDF view must not be squeezed by toolbar: '+JSON.stringify(layout));
   await page.screenshot({path:path.join(assets,'issue77_reader_original_'+width+'.png'),animations:'disabled'});
   await page.locator('.page[data-canvas-status="ready"]').first().waitFor({timeout:20000});
   assert.equal(await page.locator('.reader-tools [data-reader-mode]').getAttribute('aria-pressed'),'false');
   await page.locator('[data-reader-mode]').click();
   await page.locator('.reader-text-page[data-text-status="ready"]').first().waitFor({timeout:25000});
   const texts=await page.locator('.reader-paragraph').allTextContents(),combined=texts.join(' ');
   assert.ok(combined.indexOf('CAPITULO 1')>=0 && combined.indexOf('CAPITULO 2')>combined.indexOf('A jornada'),
     'left column must end before the right column begins');
   assert.equal(await page.locator('.reader-focused').count(),1,'first paragraph focused');
   const toc=page.locator('.reader-toc');
   assert.ok(await toc.locator('button').count()>=2,'document index derives both chapter headings');
   await page.keyboard.press('j');
   assert.equal(await page.locator('.reader-focused').getAttribute('data-reader-index'),'1');
   await page.keyboard.press('h');
   assert.equal(await page.locator('.reader-focused.reader-highlight').count(),1,'highlight follows focus');
   await page.screenshot({path:path.join(assets,'issue77_reader_text_highlight_'+width+'.png'),animations:'disabled'});
   await page.keyboard.press('z');
   await page.locator('.reader-text-page[data-text-status="ready"]').first().waitFor({timeout:20000});
   assert.equal(await page.locator('.reader-highlight').count(),0,'undo restores pre-highlight snapshot');
   page.once('dialog',dlg=>dlg.accept('Nota ligada ao segundo paragrafo'));
   await page.keyboard.press('j');
   await page.keyboard.press('n');
   assert.match(await page.locator('.reader-marginalia').first().innerText(),/Nota ligada ao segundo/);
   page.once('dialog',dlg=>dlg.accept('#edital'));
   await page.keyboard.press('t');
   assert.ok(await page.locator('.reader-tag').count()>=1,'tag is shown beside passage');
   const before=await toc.isVisible();
   await page.keyboard.press('[');
   assert.notEqual(await toc.isVisible(),before,'keyboard bracket toggles index');
   await page.locator('[data-reader-mode]').click();
   await page.locator('.page[data-canvas-status="ready"]').first().waitFor({timeout:20000});
   assert.equal(await page.locator('.reader-text-page').count(),0,'original PDF canvas can be restored');
   await page.locator('[data-reader-mode]').click();
   await page.locator('.reader-text-page[data-text-status="ready"]').first().waitFor({timeout:20000});
   assert.match(await page.locator('.reader-marginalia').first().innerText(),/Nota ligada ao segundo/,'text annotations survive switch');
   await page.screenshot({path:path.join(assets,'issue77_reader_marginalia_'+width+'.png'),animations:'disabled'});
   await page.goto(base+'#/espaco',{waitUntil:'domcontentloaded'});
   await page.locator('.home-editorial').waitFor({timeout:20000});
   assert.equal(await page.locator('.reader-tools').count(),0,'reader tools are removed after leaving document');
   report.checks.push({width,case:'real PDF parsing and order, j/k, h/z, n/t, toc, canvas switch, cleanup'});
  }finally{await context.close();}
 }
 assert.deepEqual(report.errors,[],'no uncaught JavaScript errors');
}finally{
 await browser.close();
 await writeFile(path.join(root,'issue77_reader_e2e.json'),JSON.stringify(report,null,2)+'\n');
}
