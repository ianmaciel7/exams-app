#!/usr/bin/env python3
"""Append verified Issue #100 before/after Chromium evidence to the planning board.

The source of truth is board.json; BOARD.md is generated by board_to_md.py.
Only accepts actual PNG screenshots from the E2E workflow, never placeholders.
"""
from __future__ import annotations
import json
import struct
from pathlib import Path

root = Path(__file__).resolve().parents[1] / "prototypes" / "board-exam-app"
data_path = root / "board.json"
data = json.loads(data_path.read_text(encoding="utf-8"))
elements, order = data["elements"], data["order"]
title = "32. Questões e Simulados — Issue #100: unificação dos fluxos e evidência E2E"
previous = next(((k, v) for k, v in elements.items() if v.get("type") == "container" and v.get("text") == title), None)
if previous:
    key, container = previous
    dx = 15000 - container["x"]
    if dx:
        # The original 10200px position overlapped an unrelated Readwise
        # dossier (e1091-e1093) in board_to_md's geometry ownership algorithm.
        start = order.index(key)
        own = order[start:start + 22]  # container + provenance + 10 image/caption pairs
        assert own[0] == key and sum(elements[k].get("type") == "image" for k in own) == 10
        for own_key in own:
            elements[own_key]["x"] += dx
        data_path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print("Relocated evidence section to x=15000 without moving older dossier elements.")
    else:
        print("Evidence section already exists — idempotent run.")
    raise SystemExit(0)

pairs = [
    (
        ("before_global", "ANTES: fluxo global separado da lista de objetos"),
        ("after_global", "DEPOIS: banco unificado com filtros e status rápidos"),
    ),
    (
        ("before_manual", "ANTES: busca de questão manual sem resultados na prática global"),
        ("after_manual", "DEPOIS: questão manual encontrada e renderizada no mesmo fluxo"),
    ),
    (
        ("before_simulado", "ANTES: configurador restrito à prova oficial Dataprev"),
        ("after_simulado", "DEPOIS: banco completo, quantidade, tempo e ordem configuráveis"),
    ),
    (
        ("after_answer", "DEPOIS: resposta da questão manual, feedback e persistência"),
        ("after_contexto", "DEPOIS: mesma questão manual e filtro no contexto do concurso"),
    ),
    (
        ("after_manual_simulado", "DEPOIS: simulado criado a partir do filtro da questão manual"),
        ("after_erros", "DEPOIS: atalho de erros inclui resposta manual incorreta"),
    ),
]
for pair in pairs:
    for name, _ in pair:
        image = root / "assets" / f"issue100_{name}.png"
        raw = image.read_bytes()
        if len(raw) < 10000 or raw[:8] != b"\x89PNG\r\n\x1a\n":
            raise SystemExit(f"Invalid or suspiciously small screenshot: {image}")
        width, height = struct.unpack(">II", raw[16:24])
        if width < 600 or height < 400:
            raise SystemExit(f"Invalid screenshot dimensions: {image} {width}x{height}")

next_id = max(int(k[1:]) for k in elements if k.startswith("e") and k[1:].isdigit())
def add(element):
    global next_id
    next_id += 1
    key = f"e{next_id}"
    elements[key] = element
    order.append(key)

x0, y0 = 15000, 11000
add({"type": "container", "color": "white", "text": title, "x": x0, "y": y0, "w": 1650, "h": 5 * 540 + 145})
add({
    "type": "text", "size": "small",
    "text": (
        "Fonte: Playwright Chromium 1366×900 (DPR 1), comparação da dev anterior "
        "e da branch de PR. Screenshots produzidos por tests/study-unification.e2e.mjs. "
        "Testes: busca oficial+manual, resposta, reload, lista contextual, criar simulado "
        "pelo filtro, quantidade/tempo e status de erros. Não representam inspeção do "
        "QConcursos, Capacities ou conformidade WCAG."
    ), "x": x0 + 22, "y": y0 + 12, "w": 1550, "h": 90,
})
for row, pair in enumerate(pairs):
    y = y0 + 100 + row * 540
    for column, (stem, caption) in enumerate(pair):
        x = x0 + 20 + column * 810
        add({
            "type": "image", "src": "/_blob/issue100_" + stem,
            "x": x, "y": y, "w": 760, "h": 445,
        })
        add({
            "type": "text", "size": "small",
            "text": caption + " | PNG real: assets/issue100_" + stem + ".png",
            "x": x, "y": y + 452, "w": 760, "h": 50,
        })
data_path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print(f"Added {len(pairs) * 2} verified screenshots and textual explanations for #100.")
